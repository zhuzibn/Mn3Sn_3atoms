function report = compare_to_baseline(candidate,suite,reference_root)
%COMPARE_TO_BASELINE Full inventory/input/state/clock checks; errors fail batch runs.
if nargin<2, suite='quick'; end
assert(ischar(suite) && ismember(suite,{'quick','extended'}), ...
    'Mn3SnBenchmark:Suite','suite must be quick or extended.');
if nargin<3, [manifest,root]=read_baseline(); else, [manifest,root]=read_baseline(reference_root); end
cases=manifest.cases(strcmp({manifest.cases.suite},suite));
assert(isfile(fullfile(candidate,'suite.json')), ...
    'Mn3SnBenchmark:Inventory','Missing candidate suite inventory.');
inventory=jsondecode(fileread(fullfile(candidate,'suite.json')));
assert(inventory.schema==1 && strcmp(inventory.suite,suite) && ...
    strcmp(inventory.baseline_id,manifest.id) && ...
    isequal(string(inventory.cases(:)),string({cases.name})'), ...
    'Mn3SnBenchmark:Inventory','Missing, duplicated or incompatible candidate cases.');
report=struct('passed',true,'suite',suite,'cases',struct('name',{},'spin_max_abs',{},'norm_max_abs',{}));
ignored={'Dx','Dy','Dz','IMAPMA','enable_Hk_x','inita_phi','inita_theta','initb_phi','initb_thetb'};
for k=1:numel(cases)
    c=cases(k); ref=load(fullfile(root,'cases',[c.name,'.mat']),'reference'); ref=ref.reference;
    path=fullfile(candidate,c.name,'final.mat');
    assert(isfile(path),'Mn3SnBenchmark:Inventory','Missing case: %s',c.name);
    loaded=load(path,'result');
    assert(isfield(loaded,'result'),'Mn3SnBenchmark:Schema','Missing result structure.');
    a=loaded.result;
    assert(a.schema_version==1 && isequal(a.state_order,ref.state_order) && ...
        isequal(a.component_order,ref.component_order) && strcmp(a.units.time,'s'), ...
        'Mn3SnBenchmark:Schema','Incompatible schema, state order or units.');
    assert(isequal(a.config,reference_config(ref)) && isequal(a.initial_m,ref.initial_m), ...
        'Mn3SnBenchmark:Inputs','Incompatible configuration or initial state: %s',c.name);
    fields=setdiff(fieldnames(ref.inputs),ignored);
    assert(isequal(sort(fieldnames(a.effective_inputs)),sort(fields)), ...
        'Mn3SnBenchmark:Inputs','Effective input inventory differs.');
    for j=1:numel(fields)
        name=fields{j};
        assert(isequal(a.effective_inputs.(name),ref.inputs.(name)), ...
            'Mn3SnBenchmark:Inputs','Effective input differs: %s/%s',c.name,name);
    end
    validate_arrays(ref.mmx,ref.mmy,ref.mmz,ref.initial_m);
    validate_arrays(a.mmx,a.mmy,a.mmz,a.initial_m);
    assert(isequal(size(a.mmx),size(ref.mmx)), ...
        'Mn3SnBenchmark:Shape','Trajectory shape differs.');
    err=max(abs([a.mmx,a.mmy,a.mmz]-[ref.mmx,ref.mmy,ref.mmz]),[],'all');
    assert(err<1e-10,'Mn3SnBenchmark:Trajectory','Trajectory differs: %s, error %.17g',c.name,err);
    n=ref.inputs.totstep; index=1:ref.inputs.savestep:n;
    assert(numel(a.time_s)==numel(index),'Mn3SnBenchmark:Clock','Wrong number of timestamps.');
    legacy=linspace(0,ref.inputs.runtime,n); physical=(index-1)*ref.inputs.tstep;
    units=struct('time','s','field','T','current_density','A/m^2', ...
        'magnetization','emu/cm^3','energy','J','length','m','spin','dimensionless');
    assert(isequal(a.units,units) && strcmp(a.solver.method,'rk4') && ...
        a.solver.tstep==ref.inputs.tstep && a.solver.sample_stride==ref.inputs.savestep && ...
        a.solver.updates==n-1 && a.solver.requested_end_s==ref.inputs.runtime && ...
        a.solver.integrated_end_s==(n-1)*ref.inputs.tstep && ...
        a.solver.sampled_end_s==physical(end) && ~a.solver.thermal_enabled && ...
        strcmp(a.solver.drive_policy,'frozen per RK4 step') && ...
        strcmp(a.solver.normalization,'after each complete step') && ...
        isequal(a.text.sample_steps,ref.inputs.tstepcount:ref.inputs.tstepcount:n-1), ...
        'Mn3SnBenchmark:Metadata','Units or solver/text sampling metadata differ.');
    check_clock(ref.time_s,physical); check_clock(ref.legacy_tt,legacy(index));
    check_clock(a.time_s,ref.time_s); check_clock(a.legacy_tt,ref.legacy_tt);
    assert(isequal(a.provenance.rng_before,a.provenance.rng_after), ...
        'Mn3SnBenchmark:RNG','Deterministic run changed RNG state.');
    text=fullfile(candidate,c.name,'result.txt');
    assert(isfile(text) && strcmp(mn3sn_sha256(text),ref.text_sha256) && ...
        strcmp(a.text.sha256,ref.text_sha256), ...
        'Mn3SnBenchmark:Text','Legacy text output differs: %s',c.name);
    report.cases(k)=struct('name',c.name,'spin_max_abs',err, ...
        'norm_max_abs',max(abs(sqrt(a.mmx.^2+a.mmy.^2+a.mmz.^2)-1),[],'all'));
    fprintf('PASS %s, all spin samples max error %.17g\n',c.name,err);
end
end

function validate_arrays(x,y,z,initial)
assert(isa(x,'double') && isa(y,'double') && isa(z,'double') && ...
    isreal(x) && isreal(y) && isreal(z) && isequal(size(x),size(y),size(z)) && ...
    size(x,2)==6 && ~isempty(x) && all(isfinite([x,y,z]),'all'), ...
    'Mn3SnBenchmark:Arrays','Malformed/nonfinite trajectory.');
assert(isequal([x(1,:)',y(1,:)',z(1,:)'],initial), ...
    'Mn3SnBenchmark:Initial','First sample differs from initial state.');
assert(max(abs(sqrt(x.^2+y.^2+z.^2)-1),[],'all')<1e-12, ...
    'Mn3SnBenchmark:Norm','Raw spin norms violate the contract.');
end

function check_clock(a,b)
assert(isreal(a) && isequal(size(a),size(b)) && all(isfinite(a)) && ...
    all(isfinite(b)) && a(1)==0 && b(1)==0 && all(diff(a)>0) && all(diff(b)>0), ...
    'Mn3SnBenchmark:Clock','Invalid clock shape/values.');
assert(max(abs(a(:)-b(:)))<=32*eps(max(abs(b))), ...
    'Mn3SnBenchmark:Clock','Saved timestamp values differ.');
end

function cfg = mn3sn_default_config()
%MN3SN_DEFAULT_CONFIG Complete inputs for the supported deterministic model.
% Fields are in seconds, tesla, A/m^2, joules, metres, and emu/cm^3 as noted.
root=fileparts(mfilename('fullpath'));
run(fullfile(root,'conf_file.m'));
run(fullfile(root,'constantfile.m'));
cfg=struct('solver','rk4','runtime',5000e-12,'tstep',5e-15,'savestep',50, ...
    'starttime',1000e-12,'pulsewidth',3000e-12,'risetime',0e-15,'downtime',0e-15, ...
    'Ms_Fe',441.85,'Ms_Gd',441.85,'alp',0.003,'tFL',30e-9, ...
    'Hex_1',0,'Hex_2',100.812,'hk_constant',0.196*1e-3*ele, ...
    'DMI_constant',0.833*1e-3*ele,'Hext',[0,0.0250,0], ...
    'thetaSH',0.06,'jc_SOT',50e9,'jc_SOT2',0e12, ...
    'SOT_DLT',SOT_DLT,'SOT_FLT',SOT_FLT,'STT_DLT',STT_DLT,'STT_FLT',STT_FLT, ...
    'dipolee',dipolee,'thermalnois',thermalnois,'dimensionlessLLG',dimensionlessLLG);
a=210/180*pi; b=150/180*pi; phi=90/180*pi;
cfg.initial_m=[sin(a)*cos(phi),sin(a)*sin(phi),cos(a); ...
    sin(a+120/180*pi)*cos(phi),sin(a+120/180*pi)*sin(phi),cos(a+120/180*pi); ...
    sin(a+240/180*pi)*cos(phi),sin(a+240/180*pi)*sin(phi),cos(a+240/180*pi); ...
    sin(b)*cos(phi),sin(b)*sin(phi),cos(b); ...
    sin(b+240/180*pi)*cos(phi),sin(b+240/180*pi)*sin(phi),cos(b+240/180*pi); ...
    sin(b+120/180*pi)*cos(phi),sin(b+120/180*pi)*sin(phi),cos(b+120/180*pi)];
end

function result = mn3sn_run(cfg, output_dir)
%MN3SN_RUN Run the deterministic six-vector model in a fresh output directory.
repo=fileparts(mfilename('fullpath'));
assert(strcmpi(which('mn3sn_validate_config'),fullfile(repo,'mn3sn_validate_config.m')), ...
    'Mn3Sn:ShadowedSource','Unexpected mn3sn_validate_config resolution.');
assert(strcmpi(which('mn3sn_resolve_path'),fullfile(repo,'mn3sn_resolve_path.m')), ...
    'Mn3Sn:ShadowedSource','Unexpected mn3sn_resolve_path resolution.');
mn3sn_validate_config(cfg);
if nargin<2
    parent=fullfile(repo,'.sisyphus','runs');
    if ~isfolder(parent), mkdir(parent); end
    output_dir=fullfile(parent,char(java.util.UUID.randomUUID()));
end
assert(ischar(output_dir) && isrow(output_dir) && ~isempty(output_dir), ...
    'Mn3Sn:InvalidOutput','output_dir must be a nonempty character path.');
output_dir=mn3sn_resolve_path(output_dir);
baseline=mn3sn_resolve_path(fullfile(repo,'benchmark','baseline'));
assert(~strcmpi(output_dir,baseline) && ~startsWith(lower(output_dir),lower([baseline,filesep])), ...
    'Mn3Sn:ProtectedBaseline','Cannot write in the accepted baseline.');
assert(~isfolder(output_dir) && ~isfile(output_dir), ...
    'Mn3Sn:OutputExists','Output destination already exists: %s',output_dir);
assert(isfolder(fileparts(output_dir)),'Mn3Sn:InvalidOutput','Output parent must exist.');
assert(java.io.File(output_dir).mkdir(),'Mn3Sn:InvalidOutput','Cannot reserve output directory.');
old=pwd; oldpath=path; cleanup=onCleanup(@() restore_context(old,oldpath));
addpath(repo,'-begin'); cd(output_dir);
for name={'field_eta','LLG_solver','rk4_4llg','constantfile','pulsee','Hpulsee'}
    assert(strcmpi(which(name{1}),fullfile(repo,[name{1},'.m'])), ...
        'Mn3Sn:ShadowedSource','Unexpected source resolution: %s',name{1});
end
provenance=source_info(repo);
provenance.rng_before=rng; timer=tic;
[result,text_rows]=integrate(cfg);
provenance.elapsed_s=toc(timer); provenance.rng_after=rng;
assert(all(isfinite([result.mmx,result.mmy,result.mmz]),'all'), ...
    'Mn3Sn:NonfiniteTrajectory','Integration produced nonfinite states.');
assert(max(abs(sqrt(result.mmx.^2+result.mmy.^2+result.mmz.^2)-1),[],'all')<1e-12, ...
    'Mn3Sn:InvalidNorm','Integration violated the unit-spin contract.');
result.schema_version=1; result.config=cfg; result.initial_m=cfg.initial_m;
result.output_dir=output_dir; result.provenance=provenance;
result.state_order={'ma1','ma2','ma3','mb1','mb2','mb3'};
result.component_order={'x','y','z'};
result.units=struct('time','s','field','T','current_density','A/m^2', ...
    'magnetization','emu/cm^3','energy','J','length','m','spin','dimensionless');
result.constant_units=struct('gam','rad/(s T)','ele','C','mub','J/T', ...
    'mu_0','T m/A','kb','J/K','hbar','eV s', ...
    'hbar_torque_convention','The legacy numeric hbar is hbar_SI/e in V s; no additional division by charge.');
e=result.effective_inputs;
result.solver=struct('method','rk4','tstep',cfg.tstep,'sample_stride',cfg.savestep, ...
    'updates',e.totstep-1,'requested_end_s',cfg.runtime, ...
    'integrated_end_s',(e.totstep-1)*cfg.tstep,'sampled_end_s',result.time_s(end), ...
    'drive_policy','frozen per RK4 step','normalization','after each complete step', ...
    'thermal_enabled',false);
result.limitations={'Legacy labels differ from physical integration times.', ...
    'Text saves two active spins at a different state index from MAT sampling.', ...
    'Only the documented deterministic model is supported; provenance is not physics validation.'};
text_file=fullfile(output_dir,'result.txt');
fid=fopen(text_file,'w'); assert(fid>=0,'Mn3Sn:WriteFailed','Cannot create result.txt.');
close_text=onCleanup(@() fclose(fid));
fprintf(fid,'%4.4f %8.4f %12.4f %16.4f %20.4f %24.4f %28.4f\n',text_rows');
clear close_text;
result.text=struct('file',text_file,'sha256',mn3sn_sha256(text_file), ...
    'sample_steps',e.tstepcount:e.tstepcount:e.totstep-1, ...
    'columns',{{'legacy_time_ps','ma1_x','ma1_y','ma1_z','ma2_x','ma2_y','ma2_z'}}, ...
    'physical_time_rule','sample_steps * tstep', ...
    'legacy_label_rule','linspace(0,runtime,totstep) at sample_steps, in ps');
save(fullfile(output_dir,'final.mat'),'result','-v7');
end

function restore_context(folder,search_path)
cd(folder); path(search_path);
end

function info=source_info(repo)
info=struct('created_utc',char(datetime('now','TimeZone','UTC', ...
    'Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')), ...
    'matlab',version,'release',version('-release'),'computer',computer,'toolboxes',ver, ...
    'processor_identifier',getenv('PROCESSOR_IDENTIFIER'), ...
    'logical_processors',getenv('NUMBER_OF_PROCESSORS'));
info.hardware_note='Empty environment fields mean the host did not supply that value.';
for query={'head','branch','status'}
    switch query{1}
        case 'head', command='rev-parse HEAD';
        case 'branch', command='branch --show-current';
        case 'status', command='status --porcelain';
    end
    [code,value]=system(sprintf('git -C "%s" %s',repo,command));
    info.git.(query{1})=struct('exit_status',code,'output',strtrim(value));
end
names={'main.m','mn3sn_run.m','mn3sn_default_config.m','mn3sn_validate_config.m', ...
    'mn3sn_sha256.m','mn3sn_resolve_path.m','conf_file.m','constantfile.m','field_eta.m', ...
    'LLG_solver.m','rk4_4llg.m','pulsee.m','Hpulsee.m'};
info.sources=struct('name',{},'path',{},'sha256',{});
for k=1:numel(names)
    filename=fullfile(repo,names{k});
    assert(strcmpi(which(names{k}),filename),'Mn3Sn:ShadowedSource', ...
        'Unexpected source resolution: %s',names{k});
    info.sources(k)=struct('name',names{k},'path',filename,'sha256',mn3sn_sha256(filename));
end
end

function [result,text_rows]=integrate(cfg)
constantfile;
runtime=cfg.runtime; tstep=cfg.tstep; savestep=cfg.savestep;
scheduledoutput=tstep*savestep; tstepcount=round(scheduledoutput/tstep);
starttime=cfg.starttime; endtime=runtime; pulsewidth=cfg.pulsewidth;
risetime=cfg.risetime; downtime=cfg.downtime;
LFL=50e-9; WFL=50e-9; tFL=cfg.tFL;
LHM=LFL*1.1; WHM=WFL*1.1; tHM=7e-9;
Ms_Fe=cfg.Ms_Fe; Ms_Gd=cfg.Ms_Gd; alp=cfg.alp;
Hex_1=cfg.Hex_1; Hex_2=cfg.Hex_2;
Hk_Fe_x=0; Hk_Fe_y=0; Hk_Fe_z=0; Hk_Gd_x=0; Hk_Gd_y=0; Hk_Gd_z=0;
hk_constant=cfg.hk_constant; hk6=2*hk_constant/(3*mub);
DMI_constant=cfg.DMI_constant; DMI=DMI_constant/(3*mub);
Hext=cfg.Hext; Hstarttime=starttime; Hendtime=runtime; Hpulsewidth=pulsewidth;
Hext_pulse=Hpulsee(Hstarttime,Hendtime,tstep,Hpulsewidth,Hext);
totstep=round(runtime/tstep); unitstep=round(totstep/(runtime*1e13));
jc_STT=0e9; PolFL=0.4; PolSTT=[0,0,1]; facFLT_STT=0;
thetaSH=cfg.thetaSH; lambdaSF=5e-9; polSOTD_Fe=[1,0,0]; polSOTD_Gd=[0,0,0];
jc_SOT=cfg.jc_SOT; jc_SOT2=cfg.jc_SOT2;
polSOTF_Fe=[0,0,-1]; polSOTF_Gd=[-1,0,0]; facFLT_SHE=double(cfg.SOT_FLT);
jc_SOTpulse=pulsee(starttime,endtime,tstep,pulsewidth,risetime,downtime,jc_SOT);
ma_init1=cfg.initial_m(1,:); ma_init2=cfg.initial_m(2,:); ma_init3=cfg.initial_m(3,:);
mb_init1=cfg.initial_m(4,:); mb_init2=cfg.initial_m(5,:); mb_init3=cfg.initial_m(6,:);
mmmPL=[0,0,1]; TT=1000; K12Dipole=zeros(3,3); Demag_=zeros(3,3);
thermalnois=cfg.thermalnois; dimensionlessLLG=cfg.dimensionlessLLG;
flags=struct('SOT_DLT',cfg.SOT_DLT,'STT_DLT',cfg.STT_DLT,'dipolee',cfg.dipolee);
% Explicit record of every input consumed by the existing integrator/fields.
effective=struct('runtime',runtime,'tstep',tstep,'savestep',savestep, ...
    'scheduledoutput',scheduledoutput,'tstepcount',tstepcount,'totstep',totstep, ...
    'starttime',starttime,'endtime',endtime,'pulsewidth',pulsewidth, ...
    'risetime',risetime,'downtime',downtime,'LFL',LFL,'WFL',WFL,'tFL',tFL, ...
    'LHM',LHM,'WHM',WHM,'tHM',tHM,'Ms_Fe',Ms_Fe,'Ms_Gd',Ms_Gd,'alp',alp, ...
    'Hex_1',Hex_1,'Hex_2',Hex_2,'Hk_Fe_x',Hk_Fe_x,'Hk_Fe_y',Hk_Fe_y,'Hk_Fe_z',Hk_Fe_z, ...
    'Hk_Gd_x',Hk_Gd_x,'Hk_Gd_y',Hk_Gd_y,'Hk_Gd_z',Hk_Gd_z, ...
    'hk_constant',hk_constant,'hk6',hk6,'DMI_constant',DMI_constant,'DMI',DMI, ...
    'Hext',Hext,'Hstarttime',Hstarttime,'Hendtime',Hendtime,'Hpulsewidth',Hpulsewidth, ...
    'Hext_pulse',Hext_pulse,'jc_SOTpulse',jc_SOTpulse,'unitstep',unitstep, ...
    'jc_STT',jc_STT,'PolFL',PolFL,'PolSTT',PolSTT,'facFLT_STT',facFLT_STT, ...
    'thetaSH',thetaSH,'lambdaSF',lambdaSF,'polSOTD_Fe',polSOTD_Fe,'polSOTD_Gd',polSOTD_Gd, ...
    'jc_SOT',jc_SOT,'jc_SOT2',jc_SOT2,'polSOTF_Fe',polSOTF_Fe,'polSOTF_Gd',polSOTF_Gd, ...
    'facFLT_SHE',facFLT_SHE,'ma_init1',ma_init1,'ma_init2',ma_init2,'ma_init3',ma_init3, ...
    'mb_init1',mb_init1,'mb_init2',mb_init2,'mb_init3',mb_init3,'mmmPL',mmmPL,'TT',TT, ...
    'K12Dipole',K12Dipole,'Demag_',Demag_,'thermalnois',thermalnois,'dimensionlessLLG',dimensionlessLLG, ...
    'SOT_DLT',cfg.SOT_DLT,'SOT_FLT',cfg.SOT_FLT,'STT_DLT',cfg.STT_DLT,'STT_FLT',cfg.STT_FLT, ...
    'dipolee',cfg.dipolee,'gam',gam,'ele',ele,'mub',mub,'mu_0',mu_0,'hbar',hbar,'kb',kb);
rk4_4llg;
text_rows=legacy_text_rows;
result=struct('effective_inputs',effective,'mmx',mmx,'mmy',mmy,'mmz',mmz, ...
    'legacy_tt',tt,'time_s',(0:savestep:totstep-1)*tstep);
end
